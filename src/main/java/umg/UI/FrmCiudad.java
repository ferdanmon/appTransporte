    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        //crear objeto de la clase ciudad 
        Ciudad ciudad = new Ciudad();
        ciudad.setNombre(txtNombre.getText());
        
        //crear el objeto DAO para almacenar los datos a partir de la clase CiudadDAO
        CiudadDAO dao= new CiudadDAO();
        try{
            //almacenar LOS DATOS
            dao.insertar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            
            txtNombre.setText("");
            cargarCiudades();
            
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al guardar");
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idCiudad==0){
            JOptionPane.showMessageDialog(this, "Por favor selecciona una ciudad de la tabla");
            return;
        }
        try{
            Ciudad ciudad = new Ciudad();
            //capturar los datos 
            ciudad.setIdCiudad(idCiudad);
            ciudad.setNombre(txtNombre.getText());
            //crear el dao
            CiudadDAO daoac=new CiudadDAO();
            daoac.actualizar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos actualizados");
            idCiudad=0;
            //limpiar cajas de texto
            txtNombre.setText("");
            txtID.setText("");
            tblCiudad.clearSelection();
            cargarCiudades();
        }catch(SQLException exp){
            
        }
      
    }//GEN-LAST:event_btnActualizarActionPerformed
    
    private void cargarCiudades(){
            CiudadDAO listarciudades =new CiudadDAO();
            try{
                List <Ciudad> lista= listarciudades.listar();
                DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
                modelo.setRowCount(0);
                //agregar datod a la tabla 
                for (Ciudad c: lista){
                    modelo.addRow(new Object []{
                    c.getIdCiudad(),
                    c.getNombre()
                });
                }
                
            }catch (SQLException exp){
                
            }
        }
    
    private void tblCiudadMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCiudadMouseClicked
        int fila = tblCiudad.getSelectedRow();
        if(fila>=0){
            idCiudad=Integer.parseInt(tblCiudad.getValueAt(fila,0).toString());
            txtID.setText(tblCiudad.getValueAt(fila, 0).toString());
            txtNombre.setText(tblCiudad.getValueAt(fila, 1).toString());
        }
    }//GEN-LAST:event_tblCiudadMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idCiudad==0){
            JOptionPane.showMessageDialog(this,  "Por favor seleccione una ciudad de la tabla");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "Esta seguro de eliminar la ciudad ?", "Confirmacion de eliminacion", JOptionPane.YES_NO_CANCEL_OPTION,JOptionPane.QUESTION_MESSAGE);
        if (respuesta==JOptionPane.YES_OPTION){
            CiudadDAO dao=new CiudadDAO();
            try{
                dao.eliminar(idCiudad);
                JOptionPane.showMessageDialog(this, "Ciudad eliminada exitosamente");
                cargarCiudades();
                idCiudad=0;
                txtNombre.setText("");
                txtID.setText("");
                tblCiudad.clearSelection();
            }catch(SQLException exp){
                
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

