    private void tblCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamionMouseClicked
        int fila = tblCamion.getSelectedRow();
        if(fila>=0){
        idCamion = Integer.parseInt(tblCamion.getValueAt(fila, 0).toString());
        txtID.setText(tblCamion.getValueAt(fila, 0).toString());
        txtNoPlaca.setText(tblCamion.getValueAt(fila, 1).toString());
        txtModelo.setText(tblCamion.getValueAt(fila, 2).toString());
        txtTipo.setText(tblCamion.getValueAt(fila, 3) != null ? tblCamion.getValueAt(fila, 3).toString() : "");
        txtPotencia.setText(tblCamion.getValueAt(fila, 4) != null ? tblCamion.getValueAt(fila, 4).toString() : "");
        }
    }//GEN-LAST:event_tblCamionMouseClicked

    private void cargarCamiones(){
    CamionDAO dao=new CamionDAO();
    try{
        List<Camion> lista=dao.listar();
        DefaultTableModel modelo= (DefaultTableModel) tblCamion.getModel();
        modelo.setRowCount(0);
        
            for(Camion c: lista){
            modelo.addRow(new Object[]{
            c.getIdCamion(),
            c.getNoPlaca(),
            c.getModelo(),
            c.getTipo(),
            c.getPotencia()
            });
            }
        } catch (SQLException exp){
            exp.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al cargar: " + exp.getMessage());
        }
    }
