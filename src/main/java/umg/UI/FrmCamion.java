    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        Camion camion= new Camion();
        camion.setNoPlaca(txtNoPlaca.getText());
        camion.setModelo(txtModelo.getText());
        camion.setTipo(txtTipo.getText());
        
        try{
            camion.setPotencia(Integer.parseInt(txtPotencia.getText().trim()));
        } catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "La potencia debe ser un numero payor a 0");
            return;
        }
        
        CamionDAO dao=new CamionDAO();
        try{
            dao.insertar(camion);
            JOptionPane.showMessageDialog(this, "Datos cargados correctamente");
            txtNoPlaca.setText("");
            txtModelo.setText("");
            txtTipo.setText("");
            txtPotencia.setText("");
            cargarCamiones();
        } catch(SQLException exp){
            exp.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al guardar: " + exp.getMessage());
            
        
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if(idCamion==0){
            JOptionPane.showMessageDialog(this, "Debe seleccionar algun camion de la tabla");
            return;
        }
        
        try {
            Camion camion = new Camion();
            camion.setIdCamion(idCamion);
            camion.setNoPlaca(txtNoPlaca.getText());
            camion.setModelo(txtModelo.getText());
            camion.setTipo(txtTipo.getText());
            camion.setPotencia(Integer.parseInt(txtPotencia.getText()));
            
            CamionDAO dao= new CamionDAO();
            dao.actualizar(camion);
             
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            idCamion=0;
            txtID.setText("");
            txtNoPlaca.setText("");
            txtModelo.setText("");
            txtTipo.setText("");
            txtPotencia.setText("");
            tblCamion.clearSelection();
            
            cargarCamiones();
        
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Los datos se actualizaron correctamente");
        } catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "La potencia debe ser un numero valido");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if(idCamion==0){
        JOptionPane.showMessageDialog(this, "Debe seleccionar un camion de la tabla");
        return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar el camion?", "Confirmacion de eliminacion", JOptionPane.YES_NO_CANCEL_OPTION,JOptionPane.QUESTION_MESSAGE);
        if(respuesta==JOptionPane.YES_NO_CANCEL_OPTION){
            CamionDAO dao= new CamionDAO();
            try{
                dao.eliminar(idCamion);
                JOptionPane.showMessageDialog(this, "Los datos fueron eliminados correctamente");
                cargarCamiones();
                idCamion = 0;
                txtID.setText("");
                txtNoPlaca.setText("");
                txtModelo.setText("");
                txtTipo.setText("");
                txtPotencia.setText("");

                tblCamion.clearSelection();  
            } catch(SQLException exp){
                JOptionPane.showMessageDialog(this, "Error al eliminar");
            
            }
        
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

