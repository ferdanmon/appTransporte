    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        //crear objeto 
        CamioneroCamion cc= new CamioneroCamion();
        cc.setIdCamionero(Integer.parseInt(txtIdCamionero.getText()));
        cc.setIdCamion(Integer.parseInt(txtIdCamion.getText()));
        
        //crear el objeto DAO para almacenar los datos a partir de la clase CiudadDAO
        CamioneroCamionDAO dao= new CamioneroCamionDAO();
        try{
            //almacenar LOS DATOS
            dao.insertar(cc);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            
            
            txtIdCamionero.setText("");
            txtIdCamion.setText("");
            cargarCamioneroCamion();
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al guardar");
        } catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Los ID deben ser numeros enteros");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if(idCamioneroCamion==0){
            JOptionPane.showMessageDialog(this, "Pordavor seleccione un dato de la tabla");
            return;
        }
        
        try{
            CamioneroCamion cc= new CamioneroCamion();
            cc.setIdCamioneroCamion(idCamioneroCamion);
            cc.setIdCamionero(Integer.parseInt(txtIdCamionero.getText()));
            cc.setIdCamion(Integer.parseInt(txtIdCamion.getText()));
           
            CamioneroCamionDAO dao= new CamioneroCamionDAO();
            dao.actualizar(cc);
            
            JOptionPane.showMessageDialog(this, "Los datos fueron actualizados correctamente");
            
            idCamioneroCamion=0;
            //para limpiar 
            txtID.setText("");
            txtIdCamionero.setText("");
            txtIdCamion.setText("");
            tblCamioneroCamion.clearSelection();
            
            cargarCamioneroCamion();
            
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al actualizar los datos");
            
        } catch(NumberFormatException exp){
            JOptionPane.showMessageDialog(this, "Los ID deben ser numeros valdos");
        
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idCamioneroCamion == 0) {
        JOptionPane.showMessageDialog(this, "Debe seleccionar un dato de la tabla");
        return;
        }

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de eliminar el registro?","Confirmacion de eliminacion",JOptionPane.YES_NO_OPTION);

    if (respuesta != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        CamioneroCamionDAO dao = new CamioneroCamionDAO();
        dao.eliminar(idCamioneroCamion);
        JOptionPane.showMessageDialog(this, "Los datos fueron eliminados correctamente");

        cargarCamioneroCamion();
        idCamioneroCamion = 0;
        txtID.setText("");
        txtIdCamionero.setText("");
        txtIdCamion.setText("");
        tblCamioneroCamion.clearSelection();

    } catch (SQLException exp) {
        exp.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error al eliminar: " + exp.getMessage());
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamioneroCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroCamionMouseClicked
        int fila=tblCamioneroCamion.getSelectedRow();
        if(fila>=0){
            idCamioneroCamion = Integer.parseInt(tblCamioneroCamion.getValueAt(fila, 0).toString());
            txtID.setText(tblCamioneroCamion.getValueAt(fila, 0).toString());
            txtIdCamionero.setText(tblCamioneroCamion.getValueAt(fila, 1).toString());
            txtIdCamion.setText(tblCamioneroCamion.getValueAt(fila, 2) != null ? tblCamioneroCamion.getValueAt(fila, 2).toString() : "");
        
        }
    }//GEN-LAST:event_tblCamioneroCamionMouseClicked

    private void cargarCamioneroCamion (){
        CamioneroCamionDAO dao = new CamioneroCamionDAO();
        
        try{
            List<CamioneroCamion> lista = dao.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblCamioneroCamion.getModel();
            modelo.setRowCount(0);
            
            for (CamioneroCamion cc : lista) {
            modelo.addRow(new Object[]{
                cc.getIdCamioneroCamion(),
                cc.getIdCamionero(),
                cc.getIdCamion()
            });
            }
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al cargar los dattos");
        }
    }
