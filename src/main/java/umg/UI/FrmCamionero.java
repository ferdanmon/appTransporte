    private void cargarCamioneros(){
    CamioneroDAO dao=new CamioneroDAO();
    try{
        List<Camionero> lista=dao.listar();
        DefaultTableModel modelo= (DefaultTableModel) tblCamionero.getModel();
        modelo.setRowCount(0);
        
            for(Camionero c: lista){
            modelo.addRow(new Object[]{
            c.getIdCamionero(),
            c.getNombre(),
            c.getTelefono(),
            c.getDireccion(),
            c.getSalario(),
            c.getPoblacion(),
            });
            }
        } catch (SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al cargar");
        }
    }
    
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        Camionero camionero= new Camionero();
        camionero.setNombre(txtNombre.getText());
        camionero.setTelefono(txtTelefono.getText());
        camionero.setDireccion(txtDireccion.getText());
        camionero.setSalario(Double.parseDouble(txtSalario.getText()));
        camionero.setPoblacion(txtPoblacion.getText());
        
        CamioneroDAO dao = new CamioneroDAO();
        try{
            dao.insertar(camionero);
            JOptionPane.showMessageDialog(this, "Los datos fueronn almacenados correctamente");
            
            txtNombre.setText("");
            txtTelefono.setText("");
            txtDireccion.setText("");
            txtSalario.setText("");
            txtPoblacion.setText("");
            cargarCamioneros();
            
            
        } catch (SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al guardar los datos");
           
        } catch (NumberFormatException exp){
            JOptionPane.showMessageDialog(this, "El salario ingreso debe de ser un numero valido");
        }
 
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if(idCamionero==0){
            JOptionPane.showMessageDialog(this, "Pordavor seleccione un camionero de la tabla");
            return;
        }
        
        try{
            Camionero camionero= new Camionero();
            camionero.setIdCamionero(idCamionero);
            camionero.setNombre(txtNombre.getText());
            camionero.setTelefono(txtTelefono.getText());
            camionero.setDireccion(txtDireccion.getText());
            camionero.setSalario(Double.parseDouble(txtSalario.getText()));
            camionero.setPoblacion(txtPoblacion.getText());
            CamioneroDAO dao= new CamioneroDAO();
            dao.actualizar(camionero);
            
            JOptionPane.showMessageDialog(this, "Los datos fueron actualizados correctamente");
            
            idCamionero=0;
            //para limpiar 
            txtID.setText("");
            txtNombre.setText("");
            txtTelefono.setText("");
            txtDireccion.setText("");
            txtSalario.setText("");
            txtPoblacion.setText("");
            tblCamionero.clearSelection();
            
            cargarCamioneros();
            
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al actualizar los datos");
            
        } catch(NumberFormatException exp){
            JOptionPane.showMessageDialog(this, "El salario debe de ser un numero valido");
        
        }
           
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
        if(idCamionero==0){
            JOptionPane.showMessageDialog(this, "Debe seleccionar un camionero de la tabla");
            return;
        }
        
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar al camionero?", "Confirmacion de eliminacion", JOptionPane.YES_NO_OPTION);
        if(respuesta!=JOptionPane.YES_OPTION){
            return;
        }
            CamioneroDAO dao= new CamioneroDAO();
            try{
                dao.eliminar(idCamionero);
                JOptionPane.showMessageDialog(this, "Los datos fueron eliminados correctamente");
                cargarCamioneros();
                idCamionero = 0;
                txtID.setText("");
                txtNombre.setText("");
                txtTelefono.setText("");
                txtDireccion.setText("");
                txtSalario.setText("");
                txtPoblacion.setText("");
                tblCamionero.clearSelection();  
            } catch(SQLException exp){
                JOptionPane.showMessageDialog(this, "Error al eliminar");
            
            }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamioneroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroMouseClicked
        int fila = tblCamionero.getSelectedRow();
        if(fila>=0){
            idCamionero=Integer.parseInt(tblCamionero.getValueAt(fila,0).toString());
            txtID.setText(tblCamionero.getValueAt(fila, 0).toString());
            txtNombre.setText(tblCamionero.getValueAt(fila, 1).toString());
            txtTelefono.setText(tblCamionero.getValueAt(fila, 2) != null ? tblCamionero.getValueAt(fila, 2).toString() : "");
            txtDireccion.setText(tblCamionero.getValueAt(fila, 3) != null ? tblCamionero.getValueAt(fila, 3).toString() : "");
            txtSalario.setText(tblCamionero.getValueAt(fila, 4).toString());
            txtPoblacion.setText(tblCamionero.getValueAt(fila, 5) != null ? tblCamionero.getValueAt(fila, 5).toString() : "");
        }    
    }//GEN-LAST:event_tblCamioneroMouseClicked

