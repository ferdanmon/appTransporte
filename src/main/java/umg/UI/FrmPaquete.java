    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
        Paquete paquete = new Paquete();
        paquete.setDescripcion(txtDescripcion.getText());
        paquete.setDestinatario(txtDestinatario.getText());
        paquete.setDireccionEnvio(txtDireccionEnvio.getText());
        paquete.setIdCamionero(Integer.parseInt(txtIdCamionero.getText()));
        paquete.setIdCiudad(Integer.parseInt(txtIdCiudad.getText()));
        
        PaqueteDAO dao = new PaqueteDAO();
        dao.insertar(paquete);
        
        JOptionPane.showMessageDialog(this, "Los datos fueron almacenados correctamente");
        
        txtDescripcion.setText("");
        txtDestinatario.setText("");
        txtDireccionEnvio.setText("");
        txtIdCamionero.setText("");
        txtIdCiudad.setText("");
        cargarPaquetes();
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al guardar");
        } catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Los ID deben ser numeros validos");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idPaquete==0){
            JOptionPane.showMessageDialog(this, "Por favor selecciona un paquete de la tabla");
            return;
        }
        try{
            Paquete paquete = new Paquete();
            //capturar los datos 
            paquete.setIdPaquete(idPaquete);
            paquete.setDescripcion(txtDescripcion.getText());
            paquete.setDestinatario(txtDestinatario.getText());
            paquete.setDireccionEnvio(txtDireccionEnvio.getText());
            paquete.setIdCamionero(Integer.parseInt(txtIdCamionero.getText()));
            paquete.setIdCiudad(Integer.parseInt(txtIdCiudad.getText()));
            
            PaqueteDAO dao= new PaqueteDAO();
            dao.actualizar(paquete);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            
            idPaquete = 0;
            txtID.setText("");
            txtDescripcion.setText("");
            txtDestinatario.setText("");
            txtDireccionEnvio.setText("");
            txtIdCamionero.setText("");
            txtIdCiudad.setText("");
            tblPaquete.clearSelection();
            
            cargarPaquetes();
            
        }catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al actualizar los datos"); 
        } catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Los ID deben ser numeros validos");
        
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idPaquete==0){
            JOptionPane.showMessageDialog(this, "Porfavor seleccione un paquete de la tabla");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar el paquete?", "Confirmacion de eliminacion", JOptionPane.YES_NO_OPTION);
        if(respuesta==JOptionPane.YES_OPTION){
            PaqueteDAO dao= new PaqueteDAO();
            try{
                dao.eliminar(idPaquete);
                JOptionPane.showMessageDialog(this, "Paquete eliminado correctamente");
                cargarPaquetes();
                idPaquete = 0;
                txtID.setText("");
                txtDescripcion.setText("");
                txtDestinatario.setText("");
                txtDireccionEnvio.setText("");
                txtIdCamionero.setText("");
                txtIdCiudad.setText("");
                tblPaquete.clearSelection();
 
            } catch(SQLException exp){
                exp.printStackTrace();
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + exp.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblPaqueteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaqueteMouseClicked
        int fila= tblPaquete.getSelectedRow();
        if (fila >= 0) {
            idPaquete = Integer.parseInt(tblPaquete.getValueAt(fila, 0).toString());
            txtID.setText(tblPaquete.getValueAt(fila, 0).toString());
            txtDescripcion.setText(tblPaquete.getValueAt(fila, 1).toString());
            txtDestinatario.setText(tblPaquete.getValueAt(fila, 2).toString());
            txtDireccionEnvio.setText(tblPaquete.getValueAt(fila, 3).toString());
            txtIdCamionero.setText(tblPaquete.getValueAt(fila, 4).toString());
            txtIdCiudad.setText(tblPaquete.getValueAt(fila, 5).toString());
        }
    }//GEN-LAST:event_tblPaqueteMouseClicked

