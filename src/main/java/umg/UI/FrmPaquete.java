    public void cargarPaquetes (){
        PaqueteDAO dao= new PaqueteDAO();
        try {
        List<Paquete> lista = dao.listar();
        DefaultTableModel modelo = (DefaultTableModel) tblPaquete.getModel();
        modelo.setRowCount(0);
        
        for (Paquete p : lista) {
            modelo.addRow(new Object[]{
                p.getIdPaquete(),
                p.getDescripcion(),
                p.getDestinatario(),
                p.getDireccionEnvio(),
                p.getIdCamionero(),
                p.getIdCiudad()
            });
        }
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, "Error al cargar la información");
        
        }
    }
    
